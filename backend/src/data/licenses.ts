// Normalize raw license strings to known LicenseId
export function normalizeLicense(raw: string | undefined): LicenseId {
  if (!raw) return 'UNKNOWN';

  const s = raw.trim().toUpperCase().replace(/[()]/g, '');

  if (s.includes('MIT')) return 'MIT';
  if (s.includes('APACHE') && s.includes('2')) return 'Apache-2.0';
  if (s.includes('AGPL') && s.includes('3')) return 'AGPL-3.0';
  if (s.includes('GPL') && s.includes('3') && !s.includes('LGPL')) return 'GPL-3.0';
  if (s.includes('GPL') && s.includes('2') && !s.includes('LGPL')) return 'GPL-2.0';
  if (s.includes('LGPL') && s.includes('3')) return 'LGPL-3.0';
  if (s.includes('LGPL') && s.includes('2')) return 'LGPL-2.1';
  if (s.includes('BSD') && s.includes('2')) return 'BSD-2-Clause';
  if (s.includes('BSD') && s.includes('3')) return 'BSD-3-Clause';
  if (s.includes('BSD')) return 'BSD-3-Clause';
  if (s.includes('ISC')) return 'ISC';
  if (s.includes('MPL') && s.includes('2')) return 'MPL-2.0';
  if (s.includes('CDDL') && s.includes('1')) return 'CDDL-1.0';
  if (s.includes('EPL') && s.includes('2')) return 'EPL-2.0';
  if (s.includes('EPL') && s.includes('1')) return 'EPL-1.0';
  if (s.includes('CC0')) return 'CC0-1.0';
  if (s.includes('UNLICENSE')) return 'Unlicense';

  return 'UNKNOWN';
}

